export function romGlyph(ch) {
  if (ROM_ROWS[ch]) return ROM_ROWS[ch];
  const base = ch.normalize('NFD')[0];
  if (ROM_ROWS[base]) return ROM_ROWS[base];
  if (ch === '’' || ch === '‘') return ROM_ROWS["'"];
  if (ch === '“' || ch === '”') return ROM_ROWS['"'];
  if (ch === '–' || ch === '—') return ROM_ROWS['-'];
  return ROM_ROWS['■'];
}
